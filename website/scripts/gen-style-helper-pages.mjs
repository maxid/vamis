function cssClass(name) {
  return `.${String(name).replace(/:/g, '\\:')}`
}

function emitPaletteBlock(lines, prefix, opts = {}) {
  const { group = false, suffixes = [''] } = opts
  for (const [key, value] of paletteEntries()) {
    const kinds = [
      [`${prefix}text-${key}`, 'color', value],
      [`${prefix}bg-${key}`, 'background-color', value],
      [`${prefix}border-${key}`, 'border-color', value],
    ]
    for (const [raw, prop, val] of kinds) {
      const sel = group ? `.group:hover ${cssClass(raw)}` : cssClass(raw)
      if (suffixes.length === 1) {
        lines.push(`  ${sel}${suffixes[0]} { ${prop}: ${val}; }`)
      } else {
        lines.push(`  ${suffixes.map((s) => `${sel}${s}`).join(',\n  ')} { ${prop}: ${val}; }`)
      }
    }
  }
}

function emitPaletteStates(lines, devicePrefix = '') {
  emitPaletteBlock(lines, devicePrefix)
  emitPaletteBlock(lines, `${devicePrefix}hover:`, { suffixes: [':hover'] })
  emitPaletteBlock(lines, `${devicePrefix}active:`, { suffixes: ['.is-active', ':active'] })
  emitPaletteBlock(lines, `${devicePrefix}focus:`, { suffixes: [':focus'] })
  emitPaletteBlock(lines, `${devicePrefix}disabled:`, { suffixes: ['.is-disabled', ':disabled'] })
  emitPaletteBlock(lines, `${devicePrefix}group-hover:`, { group: true })
}

