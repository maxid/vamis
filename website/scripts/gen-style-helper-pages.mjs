function cssEscapeClass(name) {
  return `.${String(name).replace(/([.:/%])/g, '\\$1')}`
}

function negateInset(value) {
  if (value === '0' || value === 'auto') return value
  return value.startsWith('-') ? value.slice(1) : `-${value}`
}

function emitInsetBlock(lines, device = '') {
  for (const [name, value, numeric] of INSET_SCALE) {
    const sel = (kind) => cssEscapeClass(`${device}${kind}-${name}`)
    lines.push(`  ${sel('top')} { top: ${value}; }`)
    lines.push(`  ${sel('right')} { right: ${value}; }`)
    lines.push(`  ${sel('bottom')} { bottom: ${value}; }`)
    lines.push(`  ${sel('left')} { left: ${value}; }`)
    lines.push(
      `  ${sel('inset')} { top: ${value}; right: ${value}; bottom: ${value}; left: ${value}; }`,
    )
    lines.push(`  ${sel('inset-x')} { right: ${value}; left: ${value}; }`)
    lines.push(`  ${sel('inset-y')} { top: ${value}; bottom: ${value}; }`)
    if (!numeric) continue
    const neg = negateInset(value)
    lines.push(`  ${sel('-top')} { top: ${neg}; }`)
    lines.push(`  ${sel('-right')} { right: ${neg}; }`)
    lines.push(`  ${sel('-bottom')} { bottom: ${neg}; }`)
    lines.push(`  ${sel('-left')} { left: ${neg}; }`)
    lines.push(
      `  ${sel('-inset')} { top: ${neg}; right: ${neg}; bottom: ${neg}; left: ${neg}; }`,
    )
    lines.push(`  ${sel('-inset-x')} { right: ${neg}; left: ${neg}; }`)
    lines.push(`  ${sel('-inset-y')} { top: ${neg}; bottom: ${neg}; }`)
  }
}

