function banner(pct, status, reason) {
  const callout =
    status === '已完成' ? 'tip' : status === '未开始' ? 'danger' : pct >= 50 ? 'info' : 'warning'
  return `::: ${callout} 实现进度 ${pct}% · ${status}\n${reason}\n:::`
}

function parseUtilityClasses(css, pred) {
  const rows = []
  const seen = new Set()
  const re = /\.((?:[a-zA-Z0-9_-]|\\[./:%])+)\s*\{([^}]+)\}/g
  let match
  while ((match = re.exec(css))) {
    const name = match[1].replace(/\\(.)/g, '$1')
    if (name.includes(':')) continue
    if (pred && !pred(name, match[2])) continue
    if (seen.has(name)) continue
    seen.add(name)
    rows.push([name, match[2].trim().replace(/\s+/g, ' ')])
  }
  return rows
}

function table(rows) {
  const lines = ['| Class | Properties |', '| --- | --- |']
  for (const [name, props] of rows) {
    lines.push(`| \`${name}\` | \`${props.replace(/\|/g, '\\|')}\` |`)
  }
  return lines.join('\n')
}

function writePage({ slug, title, pct, status, reason, intro, example, rows, extra = '' }) {
  const dir = path.join(outRoot, path.dirname(slug))
  fs.mkdirSync(dir, { recursive: true })
  const body = [
    '---',
    `title: ${title}`,
    '---',
    '',
    '<!-- generated by website/scripts/gen-style-helper-pages.mjs ; do not edit -->',
    '',
    `# ${title}`,
    '',
    banner(pct, status, reason),
    '',
    intro.trim(),
    '',
    '```schema',
    example.trim(),
    '```',
    '',
    rows?.length ? '## 类名\n' : '',
    rows?.length ? table(rows) : '',
    '',
    extra.trim(),
    '',
    '响应式：`m:` / `pc:` 目前只接到间距和宽高辅助类。其它类请用 Tailwind 断点（`max-md:` / `md:`）。状态前缀见 [辅助类-状态样式](/style/state)。',
    '',
  ]
    .filter((line, i, arr) => !(line === '' && arr[i - 1] === ''))
    .join('\n')
  fs.writeFileSync(path.join(outRoot, `${slug}.md`), `${body.trim()}\n`)
}

const helpersCss = fs.readFileSync(path.join(uiSrc, 'helpers.css'), 'utf8')
const widthCss = fs.readFileSync(path.join(uiSrc, 'helpers-width.css'), 'utf8')
const heightCss = fs.readFileSync(path.join(uiSrc, 'helpers-height.css'), 'utf8')

const marginRows = parseUtilityClasses(helpersCss, (name) => {
  if (name.startsWith('min-') || name.startsWith('max-')) return false
  return (
    name === 'm-0' ||
    /^(mb|mt|ml|mr|mx|my)-0$/.test(name) ||
    name.startsWith('m-') ||
    /^m-[tblrxy](-|$)/.test(name)
  )
})
const paddingRows = parseUtilityClasses(helpersCss, (name) => name.startsWith('p-'))
const widthRows = parseUtilityClasses(widthCss, (name) =>
  name.startsWith('w-') || name.startsWith('min-w-') || name.startsWith('max-w-'),
)
const heightRows = parseUtilityClasses(heightCss, (name) =>
  name.startsWith('h-') || name.startsWith('min-h-') || name.startsWith('max-h-'),
)

