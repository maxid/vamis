import { type SchemaDoc } from './schema-type-docs'

export type TypeCatalog = {
  properties?: Record<string, SchemaDoc>
  events?: Record<string, SchemaDoc>
  actions?: Record<string, SchemaDoc>
  slots?: string[]
  formItem?: boolean
}

function doc(title: string, category: string, description: string, detail?: string): SchemaDoc {
  return { title, category, description, detail }
}

function fields(
  label: string,
  properties: Record<string, string>,
  extra: {
    slots?: string[]
    formItem?: boolean
    events?: Record<string, string>
    actions?: Record<string, string>
  } = {},
): TypeCatalog {
  const map = (src: Record<string, string> | undefined, kind: string) =>
    src
      ? Object.fromEntries(Object.entries(src).map(([key, description]) => [key, doc(key, kind, description)]))
      : undefined
  return {
    formItem: extra.formItem,
    slots: extra.slots,
    properties: map(properties, label),
    events: map(extra.events, `${label} 事件`),
    actions: map(extra.actions, `${label} 动作`),
  }
}

